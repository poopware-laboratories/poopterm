"""Prepares git's sources for Poopterm's build, in place of its Makefile:
writes the headers git's generate-*.sh scripts make (command-list.h,
config-list.h, hook-list.h) into a build directory, from the same inputs and
in the same formats, and lists the C sources of the git program as the
Makefile's LIB_OBJS, BUILTIN_OBJS, XDIFF_OBJS and REFTABLE_OBJS name them.

    python3 -I prepare.py <git source> <build directory>

Prints the sources, one a line, relative to the git source.
"""
import glob
import os
import re
import sys


def c_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def command_list(source):
    """command-list.h: each command's category bits and one-line synopsis."""
    commands = []
    with open(os.path.join(source, "command-list.txt")) as listing:
        for line in listing:
            words = line.split()
            if not words or words[0].startswith("#"):
                continue
            commands.append((words[0], words[1:]))
    categories = sorted({category for _, cats in commands for category in cats})
    out = ["/* Automatically generated by generate-cmdlist.sh */",
           "struct cmdname_help {", "\tconst char *name;", "\tconst char *help;",
           "\tuint32_t category;", "};", "", "", "/* Command categories */"]
    out += [f"#define CAT_{cat} (1UL << {bit})" for bit, cat in enumerate(categories)]
    out += ["", "", "/* Category names */", "static const char *category_names[] = {"]
    out += [f'\t"{cat}", /* (1UL << {bit}) */' for bit, cat in enumerate(categories)]
    out += ["\tNULL", "};", "", "static struct cmdname_help command_list[] = {"]
    for name, cats in commands:
        synopsis = ""
        with open(os.path.join(source, "Documentation", name + ".txt")) as doc:
            for line in doc:
                line = line.rstrip("\n")
                if line.startswith(name + " - "):
                    synopsis = line[len(name) + 3:]
                    break
        bits = "".join(f" | CAT_{cat}" for cat in cats)
        out.append(f'\t{{ "{name}", N_("{c_string(synopsis)}"), 0{bits} }},')
    out.append("};")
    return "\n".join(out) + "\n"


def config_list(source):
    """config-list.h: every configuration variable the documentation names."""
    names = []
    files = glob.glob(os.path.join(source, "Documentation", "*config.txt"))
    files += glob.glob(os.path.join(source, "Documentation", "config", "*.txt"))
    for path in files:
        with open(path) as doc:
            for line in doc:
                line = line.rstrip("\n")
                if re.match(r"^[a-zA-Z].*\..*::$", line) and "deprecated" not in line:
                    names += re.split(r",  *", line[:-2])
    out = ["/* Automatically generated by generate-configlist.sh */", "", "",
           "static const char *config_name_list[] = {"]
    out += [f'\t"{name}",' for name in sorted(names)]
    out += ["\tNULL,", "};"]
    return "\n".join(out) + "\n"


def hook_list(source):
    """hook-list.h: each hook, as a line underlined with ~ in githooks.txt."""
    hooks, previous = [], None
    with open(os.path.join(source, "Documentation", "githooks.txt")) as doc:
        for line in doc:
            line = line.rstrip("\n")
            if re.fullmatch(r"~~~~*", line) and previous is not None:
                hooks.append(previous)
            previous = line
    out = ["/* Automatically generated by generate-hooklist.sh */", "",
           "static const char *hook_name_list[] = {"]
    out += [f'\t"{hook}",' for hook in sorted(hooks)]
    out += ["\tNULL,", "};"]
    return "\n".join(out) + "\n"


def sources(source):
    """The program's C files, from the Makefile's object lists: only its
    unconditional lines, as indented ones sit inside ifdef blocks."""
    found = []
    with open(os.path.join(source, "Makefile")) as makefile:
        for line in makefile:
            match = re.match(r"^(LIB|BUILTIN|XDIFF|REFTABLE)_OBJS \+= (\S+)\.o$", line.rstrip())
            if match:
                found.append(match.group(2) + ".c")
    return found


def main(source, build):
    os.makedirs(build, exist_ok=True)
    for name, make in [("command-list.h", command_list), ("config-list.h", config_list),
                       ("hook-list.h", hook_list)]:
        with open(os.path.join(build, name), "w") as out:
            out.write(make(source))
    for path in sources(source):
        print(path)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
